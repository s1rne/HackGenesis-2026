# frozen_string_literal: true

module Routing
  # Часы прогона.
  #
  # Ограничение по интенсивности имеет смысл только во времени, а время в
  # заявках может быть, а может и не быть. Если `created_at` есть — идём по
  # нему; если нет — двигаем виртуальные часы на шаг вперёд. Так лимит
  # «7 заявок в минуту» работает в обоих случаях, а поведение остаётся
  # воспроизводимым.
  #
  # Здесь была ошибка, которую стоит держать в голове. Изначально часы не
  # позволяли времени идти назад и брали максимум из накопленного и текущей
  # отметки — казалось, что так безопаснее для неотсортированной очереди.
  # На деле это ломалось на реплее истории: часы стартовали от snapshot_at
  # провайдеров (30 июля), а все сто исторических заявок были за 29-е. Каждая
  # оказывалась «раньше» и получала одну и ту же отметку, скользящее окно
  # видело сто заявок в одну секунду, и лимит интенсивности выкашивал весь пул.
  #
  # Правильно иначе: у заявки со своей отметкой время — её собственное. Окно
  # «сколько заявок за последнюю минуту до этой» считается корректно при любом
  # порядке, а сам факт неупорядоченности — повод сказать об этом, а не
  # молча подменять данные.
  class Clock
    # Условная отметка на случай, когда времени нет ни в снимке провайдеров,
    # ни в заявках. Фиксированная, а не Time.now: иначе правила, зависящие от
    # времени суток, давали бы разный результат при каждом запуске.
    FALLBACK_ANCHOR = Time.utc(2000, 1, 1).freeze

    attr_reader :started_at, :now, :anchored_by_fallback

    def initialize(started_at: nil, step_sec: 1.0)
      @started_at = started_at
      @step = step_sec.to_f
      @now = nil
      @anchored_by_fallback = false
      @out_of_order = 0
    end

    def advance_to(operation)
      stamp = operation.created_at&.to_f

      if stamp
        @started_at ||= Time.at(stamp)
        @out_of_order += 1 if @now && stamp < @now
        @now = stamp
      else
        anchor_fallback if @started_at.nil?
        @now = (@now || @started_at.to_f) + @step
      end

      @now
    end

    # Сколько заявок пришло с отметкой раньше предыдущей. Само по себе это не
    # ошибка — очередь может быть просто не отсортирована, — но знать об этом
    # полезно: на неупорядоченных данных окно интенсивности считается по
    # времени заявки, а не по её месту в файле.
    def out_of_order_count = @out_of_order

    def to_time = Time.at(@now || FALLBACK_ANCHOR.to_f)

    private

    def anchor_fallback
      @started_at = FALLBACK_ANCHOR
      @anchored_by_fallback = true
    end
  end
end
