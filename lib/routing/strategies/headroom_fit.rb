# frozen_string_literal: true

module Routing
  module Strategies
    # Цена заявки для конкретного партнёра.
    #
    # Загрузка (`load_balance`) отвечает на вопрос «насколько партнёр занят
    # вообще». Здесь другой вопрос: сколько от его оставшегося дневного запаса
    # съедает **эта** заявка. Числа расходятся сильно. Партнёр с запасом
    # 100 000 ₽ и партнёр с запасом 1 300 000 ₽ могут иметь одинаковую
    # загрузку в процентах, но выплата на 47 000 ₽ для первого — половина
    # остатка, а для второго — три процента.
    #
    # Зачем это нужно. Целевая доля задана **по количеству** заявок, а лимит —
    # **в деньгах**. Если партнёру с узким запасом достанутся первые же крупные
    # чеки, он выберет лимит на трёх выплатах и до конца суток не возьмёт
    # больше ничего — недобрав свою долю по количеству в разы. Те же деньги,
    # потраченные на мелкие чеки, дали бы ему втрое больше заявок.
    #
    # Проверено на прогоне из шестидесяти заявок: payflow со свободными
    # 100 000 ₽ забрал семь заявок на 99 300 ₽, тогда как теми же деньгами
    # мог взять одиннадцать — ровно столько, сколько показывает его потолок
    # по ёмкости в разделе достижимости.
    #
    # Цель молчит (возвращает nil), когда дневного лимита нет вовсе: тогда
    # сравнивать не с чем, и навязывать всем нейтральное значение незачем.
    class HeadroomFit < Base
      # Доля запаса — величина с собственным смыслом: 0.47 значит «половина
      # остатка», а не «хуже соседа». Нормализация по кандидатам растянула бы
      # разницу в три процента до максимума и заставила бы цель кричать там,
      # где ей нечего сказать.
      def absolute? = true

      def raw_score(context)
        share = consumed_share(context)
        return nil if share.nil?

        (1.0 - share).clamp(0.0, 1.0)
      end

      def explain(context)
        headroom = context.state.headroom_amount
        return "дневной лимит не задан, запас неограничен" if headroom.nil?

        share = consumed_share(context)
        return "дневной запас исчерпан — заявка не помещается" if share.nil? || share >= 1.0

        "заявка съедает #{pct(share)}% оставшегося дневного запаса " \
          "(#{context.operation.amount} из #{headroom})"
      end

      private

      # Доля оставшегося дневного запаса, которую занимает эта заявка.
      # Исчерпанный запас — забота жёсткого ограничения, здесь он просто
      # даёт максимальную цену.
      def consumed_share(context)
        headroom = context.state.headroom_amount
        return nil if headroom.nil?
        return 1.0 if headroom.zero?

        context.operation.amount.ratio_of(headroom)
      end
    end
  end
end
